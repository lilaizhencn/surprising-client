import 'dart:convert';
import 'dart:io';

const languages = [
  'en',
  'zh',
  'zh-TW',
  'es',
  'fr',
  'de',
  'pt',
  'ru',
  'ar',
  'ja',
  'ko',
  'hi',
];
Set<String> placeholders(String value) => RegExp(
  r'\{[A-Za-z_][A-Za-z0-9_]*\}',
).allMatches(value).map((match) => match[0]!).toSet();
String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');

void main() {
  final root = Directory('lib/src/i18n');
  final source =
      (jsonDecode(File('${root.path}/source.json').readAsStringSync()) as List)
          .cast<String>();
  final keys = source.toSet();
  if (source.length != keys.length || source.isEmpty) {
    throw StateError('Invalid source manifest');
  }
  final catalogs = <String, Map<String, String>>{};
  for (final language in languages) {
    final value =
        (jsonDecode(
                  File(
                    '${root.path}/catalogs/$language.json',
                  ).readAsStringSync(),
                )
                as Map)
            .cast<String, String>();
    if (value.length != keys.length || !value.keys.toSet().containsAll(keys)) {
      throw StateError('Incomplete language: $language');
    }
    for (final key in keys) {
      if (value[key]!.isEmpty ||
          !placeholders(key).containsAll(placeholders(value[key]!)) ||
          !placeholders(value[key]!).containsAll(placeholders(key))) {
        throw StateError(
          'Invalid translation or placeholders: $language / $key',
        );
      }
    }
    catalogs[language] = value;
  }
  final output = StringBuffer(
    '// Generated by tool/generate_client_messages.dart. Do not edit by hand.\n',
  );
  output.writeln('const Set<String> clientSourceMessages = {');
  for (final key in source) {
    output.writeln('  ${literal(key)},');
  }
  output.writeln(
    '};\nconst Map<String, Map<String, String>> clientMessageCatalogs = {',
  );
  for (final language in languages) {
    output.writeln('  ${literal(language)}: {');
    for (final key in source) {
      output.writeln(
        '    ${literal(key)}: ${literal(catalogs[language]![key]!)},',
      );
    }
    output.writeln('  },');
  }
  output.writeln('};');
  File('${root.path}/messages.g.dart').writeAsStringSync(output.toString());
  stdout.writeln(
    'Generated ${languages.length} complete languages, ${keys.length} labels each.',
  );
}
